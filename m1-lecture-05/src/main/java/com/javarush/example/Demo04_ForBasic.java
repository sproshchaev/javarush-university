package com.javarush.example;

public class Demo04_ForBasic {
    public static void main(String[] args) {
        System.out.println("=== Числа от 0 до 19 ===");

        for (int i = 0; i < 20; i++) {
            System.out.print(i + " ");
        }

        System.out.println();
        System.out.println("Витков цикла: 20");
    }
}
